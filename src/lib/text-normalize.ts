/**
 * PDFから抽出したテキストの正規化。
 *
 * PDFの日本語フォントによっては、「行」「方」「人」などの漢字が、見た目が同じ別の文字
 * （康熙部首 U+2F00〜、CJK部首補助 U+2E80〜）として抽出される。
 * そのままだと「銀行」で検索しても「銀⾏」に一致せず、部署名「人事」の判定にも失敗するため、
 * 通常の漢字に戻す。質問文にも同じ正規化をかける。
 */

// CJK部首補助（U+2E80〜U+2EFF）にはUnicodeの互換分解が無いものが多いため、対応表で戻す
const RADICAL_SUPPLEMENT_MAP: Record<string, string> = {
  "⺟": "母", "⺠": "民", "⺢": "水", "⺣": "火", "⺩": "王", "⺫": "目", "⺬": "示", "⺭": "示",
  "⺮": "竹", "⺯": "糸", "⺰": "糸", "⺱": "网", "⺶": "羊", "⺷": "羊", "⺹": "老", "⺼": "肉",
  "⺾": "艸", "⻁": "虎", "⻂": "衣", "⻃": "西", "⻄": "西", "⻅": "見", "⻆": "角", "⻈": "言",
  "⻉": "貝", "⻊": "足", "⻋": "車", "⻌": "辶", "⻍": "辶", "⻎": "辶", "⻏": "邑", "⻐": "金",
  "⻑": "長", "⻒": "長", "⻓": "長", "⻔": "門", "⻖": "阜", "⻗": "雨", "⻘": "青", "⻙": "韋",
  "⻚": "頁", "⻛": "風", "⻜": "飛", "⻝": "食", "⻞": "食", "⻟": "食", "⻠": "食", "⻢": "馬",
  "⻣": "骨", "⻤": "鬼", "⻥": "魚", "⻦": "鳥", "⻧": "鹵", "⻨": "麦", "⻩": "黄", "⻪": "黽",
  "⻫": "斉", "⻬": "斉", "⻭": "歯", "⻮": "歯", "⻯": "竜", "⻰": "竜", "⻱": "亀", "⻲": "亀", "⻳": "亀",
};

const KANGXI_RADICALS = /[⼀-⿟]/g;
const RADICAL_SUPPLEMENT = /[⺀-⻿]/g;

export function normalizeText(text: string): string {
  return text
    .replace(KANGXI_RADICALS, (c) => c.normalize("NFKC"))
    .replace(RADICAL_SUPPLEMENT, (c) => RADICAL_SUPPLEMENT_MAP[c] ?? c.normalize("NFKC"));
}

/** 正規化しても部首の文字のまま残ったもの。取り込みレポートで警告するために使う */
export function findUnmappedRadicals(text: string): string[] {
  return [...new Set(text.match(/[⺀-⿟]/g) ?? [])];
}
